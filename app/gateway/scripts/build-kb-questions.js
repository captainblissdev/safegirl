/**
 * SafeGirl -- knowledge-base questions for the interface's Topic list
 *
 * Writes app/interface/src/content/kbQuestions.json: the id, class and
 * "User question" of every active knowledge-base entry, in knowledge-base
 * order, read through retrievalModule.loadKnowledgeBase() (so HELD content
 * is never read). It carries no answers: the Topic list submits a
 * question through the full pipeline like any other, and the answer
 * comes back from there. A gateway test fails if the file is stale.
 *
 *     node scripts/build-kb-questions.js           # write the list
 *     node scripts/build-kb-questions.js --check   # exit 1 if it is stale
 */

const fs = require("node:fs");
const path = require("node:path");

const { loadKnowledgeBase } = require("../src/retrievalModule");

const OUTPUT_FILE = path.join(
  __dirname,
  "..",
  "..",
  "interface",
  "src",
  "content",
  "kbQuestions.json",
);

/** The list to write: id, class and question only. */
function buildKbQuestions() {
  const questions = [];
  for (const [topicClass, entries] of Object.entries(loadKnowledgeBase())) {
    for (const entry of entries) {
      questions.push({ id: entry.kbId, topicClass, question: entry.question });
    }
  }
  return {
    description:
      "Questions of the active knowledge base, for the Topic list. " +
      "Generated by app/gateway/scripts/build-kb-questions.js; do not " +
      "edit by hand. No answers: a question is submitted through the " +
      "full pipeline.",
    questions,
  };
}

const serialize = (list) => `${JSON.stringify(list, null, 2)}\n`;

function main(argv) {
  const text = serialize(buildKbQuestions());

  if (argv.includes("--check")) {
    const current = fs.existsSync(OUTPUT_FILE)
      ? fs.readFileSync(OUTPUT_FILE, "utf8")
      : null;
    if (current !== text) {
      console.error(
        "app/interface/src/content/kbQuestions.json is out of date. Run: node scripts/build-kb-questions.js",
      );
      return 1;
    }
    console.log("app/interface/src/content/kbQuestions.json is up to date.");
    return 0;
  }

  fs.writeFileSync(OUTPUT_FILE, text);
  console.log(
    `Wrote ${JSON.parse(text).questions.length} questions to app/interface/src/content/kbQuestions.json`,
  );
  return 0;
}

if (require.main === module) {
  process.exitCode = main(process.argv.slice(2));
}

module.exports = { buildKbQuestions, serialize, OUTPUT_FILE };
