import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import { VitePWA } from "vite-plugin-pwa";

// PWA configuration supports NFR-06 by providing an installable,
// responsive application shell that can remain available during
// intermittent connectivity. User conversation content is not cached.
export default defineConfig({
  plugins: [
    react(),
    VitePWA({
      registerType: "autoUpdate",

      // The icons and favicons in public/ are already precached by
      // globPatterns below, so they are not added a second time.
      includeManifestIcons: false,

      workbox: {
        // Cache the generated application shell and static assets.
        // Do not add runtime caching for /api because responses may
        // contain sensitive health-related conversation content.
        globPatterns: ["**/*.{js,css,html,ico,png,svg,woff2}"],

        // Page loads (navigations) are answered with the cached app
        // shell, except the gateway's own paths: /api and /health always
        // go to the network and are never answered with index.html.
        navigateFallbackDenylist: [/^\/api(?:\/|$)/, /^\/health(?:\/|$)/],
      },

      manifest: {
        name: "SafeGirl",
        short_name: "SafeGirl",
        description: "Anonymous, confidential SRH information support",
        // The page background (body in index.css), so the browser bar and
        // the splash screen match the app.
        theme_color: "#f3efe7",
        background_color: "#f3efe7",
        display: "standalone",
        // Generated by `npm run generate-icons` (scripts/generate-icons.mjs).
        icons: [
          {
            src: "pwa-192x192.png",
            sizes: "192x192",
            type: "image/png",
            purpose: "any",
          },
          {
            src: "pwa-512x512.png",
            sizes: "512x512",
            type: "image/png",
            purpose: "any",
          },
          {
            src: "maskable-512x512.png",
            sizes: "512x512",
            type: "image/png",
            purpose: "maskable",
          },
        ],
      },
    }),
  ],

  server: {
    proxy: {
      "/api": "http://localhost:3001",
    },
  },
});
